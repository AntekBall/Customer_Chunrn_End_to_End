SELECT
    c.customer_id,
    c.churn,
    s.partition,
    c.age,
    c.gender,
    c.annual_income,
    c.education,
    c.marital_status,
    c.dependents,
    c.tenure,
    c.contract,
    c.payment_method,
    c.paperless_billing,
    c.monthlycharges,
    c.totalcharges,
    c.num_services,
    c.has_phone_service,
    c.has_internet_service,
    c.has_online_security,
    c.has_online_backup,
    c.has_device_protection,
    c.has_tech_support,
    c.has_streaming_tv,
    c.has_streaming_movies,
    c.customer_satisfaction,
    c.num_complaints,
    c.num_service_calls,
    c.late_payments,
    c.avg_monthly_gb,
    c.days_since_last_interaction,
    c.credit_score
FROM raw_customers AS c
INNER JOIN customer_split_manifest AS s
    ON c.customer_id = s.customer_id;